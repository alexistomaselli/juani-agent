-- Run against a disposable database after the stock migration.
BEGIN;
DO $$
DECLARE n integer; caught boolean;
BEGIN
  IF (SELECT stock FROM "Product" WHERE id='legacy') IS NOT NULL THEN RAISE EXCEPTION 'Legacy stock was fabricated'; END IF;
  UPDATE "Product" SET stock=10 WHERE id='legacy';
  UPDATE "Order" SET status='CANCELLED' WHERE id='legacy';
  IF (SELECT stock FROM "Product" WHERE id='legacy') <> 10 THEN RAISE EXCEPTION 'Legacy cancellation returned unreserved goods'; END IF;
  INSERT INTO "Product"(id,name,stock) VALUES ('a','A',5),('b','B',2),('unknown','Unknown',null),('inactive','Inactive',5);
  INSERT INTO "Order"(id,"productId",quantity) VALUES ('one','a',2);
  IF (SELECT stock FROM "Product" WHERE id='a') <> 3 THEN RAISE EXCEPTION 'Creation did not reserve'; END IF;
  UPDATE "Order" SET "stockReserved"=0 WHERE id='one';
  IF (SELECT "stockReserved" FROM "Order" WHERE id='one') <> 2 THEN RAISE EXCEPTION 'Client overwrote reservation'; END IF;
  UPDATE "Order" SET quantity=4 WHERE id='one';
  IF (SELECT stock FROM "Product" WHERE id='a') <> 1 THEN RAISE EXCEPTION 'Increase did not reserve delta'; END IF;
  caught:=false;
  BEGIN UPDATE "Order" SET quantity=6 WHERE id='one';
  EXCEPTION WHEN raise_exception THEN caught:=SQLERRM='JUANI_STOCK_INSUFFICIENT'; END;
  IF NOT caught OR (SELECT quantity FROM "Order" WHERE id='one') <> 4 OR (SELECT stock FROM "Product" WHERE id='a') <> 1 THEN RAISE EXCEPTION 'Insufficient stock was not atomic'; END IF;
  UPDATE "Order" SET quantity=1 WHERE id='one';
  IF (SELECT stock FROM "Product" WHERE id='a') <> 4 THEN RAISE EXCEPTION 'Reduction did not return delta'; END IF;
  UPDATE "Order" SET "productId"='b' WHERE id='one';
  IF (SELECT stock FROM "Product" WHERE id='a') <> 5 OR (SELECT stock FROM "Product" WHERE id='b') <> 1 THEN RAISE EXCEPTION 'Product swap failed'; END IF;
  UPDATE "Order" SET status='CANCELLED' WHERE id='one';
  UPDATE "Order" SET status='CANCELLED' WHERE id='one';
  IF (SELECT stock FROM "Product" WHERE id='b') <> 2 THEN RAISE EXCEPTION 'Cancellation did not return exactly once'; END IF;
  UPDATE "Order" SET status='PENDING' WHERE id='one';
  IF (SELECT stock FROM "Product" WHERE id='b') <> 1 THEN RAISE EXCEPTION 'Reactivation did not reserve'; END IF;
  DELETE FROM "Order" WHERE id='one';
  IF (SELECT stock FROM "Product" WHERE id='b') <> 2 THEN RAISE EXCEPTION 'Deleting pending did not return stock'; END IF;
  INSERT INTO "Order"(id,"productId",quantity) VALUES ('delivered','a',1);
  UPDATE "Order" SET status='DELIVERED' WHERE id='delivered';
  DELETE FROM "Order" WHERE id='delivered';
  IF (SELECT stock FROM "Product" WHERE id='a') <> 4 THEN RAISE EXCEPTION 'Deleting delivered recreated sold goods'; END IF;
  INSERT INTO "Order"(id,"productId",quantity) VALUES ('uncounted','unknown',3);
  IF (SELECT "stockReserved" FROM "Order" WHERE id='uncounted') <> 0 THEN RAISE EXCEPTION 'Uncounted product reserved invented stock'; END IF;
  UPDATE "Product" SET stock=5 WHERE id='unknown';
  UPDATE "Order" SET quantity=3 WHERE id='uncounted';
  IF (SELECT stock FROM "Product" WHERE id='unknown') <> 5 THEN RAISE EXCEPTION 'Unrelated edit retroactively reserved'; END IF;
  UPDATE "Order" SET quantity=4 WHERE id='uncounted';
  UPDATE "Order" SET status='CANCELLED' WHERE id='uncounted';
  IF (SELECT stock FROM "Product" WHERE id='unknown') <> 5 THEN RAISE EXCEPTION 'Legacy delta accounting failed'; END IF;
  UPDATE "Product" SET active=false WHERE id='inactive';
  caught:=false;
  BEGIN INSERT INTO "Order"(id,"productId",quantity) VALUES ('bad','inactive',1);
  EXCEPTION WHEN raise_exception THEN caught:=SQLERRM='JUANI_PRODUCT_UNAVAILABLE'; END;
  IF NOT caught THEN RAISE EXCEPTION 'Inactive product sold'; END IF;
  INSERT INTO "Product"(id,name,stock) VALUES ('empty','Empty',0);
  caught:=false;
  BEGIN INSERT INTO "Order"(id,"productId",quantity) VALUES ('empty','empty',1);
  EXCEPTION WHEN raise_exception THEN caught:=SQLERRM='JUANI_STOCK_INSUFFICIENT'; END;
  IF NOT caught THEN RAISE EXCEPTION 'Zero-stock product sold'; END IF;
END $$;
ROLLBACK;
